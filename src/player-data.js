const GROUP_POSITIONS = {
  GK: ['GK'],
  FB: ['RB', 'RWB'],
  CB: ['CB'],
  DM: ['DM', 'CM'],
  CM: ['CM'],
  AM: ['AM', 'CM'],
  W: ['LW', 'RW'],
  ST: ['ST']
};

const GROUP_TOP_RATING = {GK: 89, FB: 91, CB: 90, DM: 91, CM: 92, AM: 92, W: 92, ST: 91};

function activePlayers() {
  return Object.entries(ACTIVE_GROUPS).flatMap(([group, entries]) => entries.map((entry, index) => {
    const [name, positions] = Array.isArray(entry) ? entry : [entry, GROUP_POSITIONS[group]];
    const rating = Math.max(78, GROUP_TOP_RATING[group] - Math.floor(index / 5));
    return [name, '现役', positions, rating];
  }));
}

const RAW_PLAYERS = [...LEGACY_PLAYERS, ...activePlayers()];

if (RAW_PLAYERS.length !== 360) throw new Error(`球员库应为 360 人，当前为 ${RAW_PLAYERS.length} 人`);
if (new Set(RAW_PLAYERS.map(player => player[0])).size !== RAW_PLAYERS.length) throw new Error('球员库存在重名球员');

